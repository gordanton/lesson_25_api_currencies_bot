_CODE_RE = re.compile(r"[A-Za-z]{3}")


def normalize(text: str) -> str:
    cleaned = text.strip().lower().replace("ё", "е")
    cleaned = cleaned.replace("—", " ").replace("–", " ").replace("-", " ")
    return " ".join(cleaned.split())


def resolve_place(text: str) -> tuple[str, str] | None:
    """Возвращает (название для кошелька, код валюты) или None, если строку не узнать.

    Трёхбуквенный код пропускаем даже без словаря: его проверит уже сам API.
    """
    key = normalize(text)
    if key in _COUNTRIES:
        return _COUNTRIES[key]
    if _CODE_RE.fullmatch(text.strip()):
        code = text.strip().upper()
        return code, code
    return None
